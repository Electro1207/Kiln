import { readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'

/* Library build for the npm package @electro1207/kiln (see packages/kiln/package.json).
   One ESM file per source file (preserveModules), so a bundler can drop every component you
   don't import. Entries: index plus one per folder (groups/<folder>.ts), all generated by
   scripts/gen-index.mjs. Types come from tsconfig.lib.json; styles.css from scripts/build-lib.mjs. */
const src = (p: string) => fileURLToPath(new URL(`./src/kiln/${p}`, import.meta.url))

const entry: Record<string, string> = { index: src('index.ts') }
for (const f of readdirSync(src('groups'))) {
  if (f.endsWith('.ts')) entry[`groups/${f.slice(0, -3)}`] = src(`groups/${f}`)
}

export default defineConfig({
  publicDir: false,
  build: {
    outDir: 'packages/kiln/lib',
    emptyOutDir: true,
    target: 'es2023',
    minify: false,
    sourcemap: false,
    lib: { entry, formats: ['es'] },
    rollupOptions: {
      external: [/^react(\/|$)/, /^react-dom(\/|$)/, /^motion(\/|$)/, /^lucide-react(\/|$)/],
      output: {
        preserveModules: true,
        preserveModulesRoot: 'src/kiln',
        entryFileNames: '[name].js',
      },
    },
  },
})
