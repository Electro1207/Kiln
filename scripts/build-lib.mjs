#!/usr/bin/env node
/* Builds the npm package into packages/kiln. Re-runnable; nothing here edits component files.
     1. gen-index        src/kiln/index.ts and groups/*.ts
     2. vite build       packages/kiln/lib/ (js; see vite.lib.config.ts)
     3. tsc              packages/kiln/lib/ (d.ts; see tsconfig.lib.json)
     4. styles.css       tokens.css + kiln.css + an @source for lib/, so Tailwind scans the class names
     5. copies           tokens.css, CLAUDE.md, README.md, LICENSE
   Then, from packages/kiln:  npm pack   (or npm publish --provenance in CI). */
import { execFileSync } from "node:child_process";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PKG = join(ROOT, "packages/kiln");
const run = (cmd, args) => execFileSync(cmd, args, { cwd: ROOT, stdio: "inherit" });
const bin = (n) => join(ROOT, "node_modules/.bin", n);

run("node", ["scripts/gen-index.mjs"]);
run(bin("vite"), ["build", "-c", "vite.lib.config.ts"]);
run(bin("tsc"), ["-p", "tsconfig.lib.json"]);

const tokens = readFileSync(join(ROOT, "src/kiln/tokens.css"), "utf8");
const kiln = readFileSync(join(ROOT, "src/kiln/kiln.css"), "utf8");
if (!/@import "\.\/tokens\.css";\n/.test(kiln)) throw new Error('kiln.css no longer starts with @import "./tokens.css"; update scripts/build-lib.mjs');
const styles =
`/* @electro1207/kiln styles. GENERATED by scripts/build-lib.mjs from src/kiln/tokens.css and src/kiln/kiln.css.

   In your CSS, after Tailwind:
     @import "tailwindcss";
     @import "@electro1207/kiln/styles.css";

   The @source line makes Tailwind v4 scan the package's JavaScript for the class names the components use. */
@source "./lib";

` + kiln.replace(/@import "\.\/tokens\.css";\n/, "\n" + tokens + "\n");
writeFileSync(join(PKG, "styles.css"), styles);

copyFileSync(join(ROOT, "src/kiln/tokens.css"), join(PKG, "tokens.css"));
copyFileSync(join(ROOT, "src/kiln/CLAUDE.md"), join(PKG, "CLAUDE.md"));
copyFileSync(join(ROOT, "README.md"), join(PKG, "README.md"));
copyFileSync(join(ROOT, "LICENSE"), join(PKG, "LICENSE"));
console.log("build-lib: packages/kiln is ready (run `npm pack` there)");
