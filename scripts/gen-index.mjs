#!/usr/bin/env node
/* Generates the package entry points from the component sources, so nothing is listed by hand:
     src/kiln/index.ts             every public component, hook, type and helper
     src/kiln/groups/<group>.ts    the same, one file per folder (subpath exports: "@electro1207/kiln/buttons")
   Re-runnable. Run `npm run gen:index` after adding, renaming or removing a component.

   Name clashes: two files exporting the same name cannot both be re-exported from one entry. Resolve a
   clash by adding the file and name to RENAMES below; the script stops with a message if one is missing. */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const KILN = join(ROOT, "src/kiln");

/** "<path under src/kiln, no extension>:<exported name>" -> public name. */
const RENAMES = {
  "components/communication/ChatThread:ChatMessage": "ChatThreadMessage", // the ai/ChatMessage component keeps the name
  "components/shared/Anchored:Placement": "AnchoredPlacement",
  "components/shared/useOverlay:Placement": "OverlayPlacement",
};

const CORE = ["cn", "motion", "controllable", "theme", "colorway"];

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** Top-level exports of one file. Everything the sources use is a plain `export function|const|class|type|interface`. */
function exportsOf(file) {
  const src = readFileSync(file, "utf8");
  const out = [];
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(function|const|let|class|type|interface)\s+(\w+)/gm))
    out.push({ name: m[2], type: m[1] === "type" || m[1] === "interface" });
  if (/^export\s+(default|\*|\{|type\s*\{)/m.test(src))
    throw new Error(`${relative(ROOT, file)}: default exports and export lists are not handled by gen-index.mjs`);
  return out;
}

const modules = [];
for (const base of CORE) {
  const f = ["ts", "tsx"].map((e) => join(KILN, `${base}.${e}`)).find((p) => { try { return statSync(p); } catch { return false; } });
  if (f) modules.push({ group: "core", id: base, file: f });
}
const compRoot = join(KILN, "components");
for (const f of walk(compRoot).sort()) {
  if (!/\.tsx?$/.test(f) || f.endsWith(".d.ts")) continue;
  const rel = relative(compRoot, f);
  modules.push({ group: rel.split("/")[0], id: `components/${rel.replace(/\.tsx?$/, "")}`, file: f });
}

for (const m of modules) {
  m.exports = exportsOf(m.file).map((e) => ({ ...e, as: RENAMES[`${m.id}:${e.name}`] ?? e.name, from: m.id }));
  m.spec = "./" + relative(KILN, m.file).replace(/\.tsx?$/, "");
}
const used = new Map();
const clashes = [];
for (const m of modules) for (const e of m.exports) {
  if (used.has(e.as)) clashes.push(`  "${e.as}" is exported by ${used.get(e.as)} and ${m.id}`);
  else used.set(e.as, m.id);
}
for (const k of Object.keys(RENAMES)) if (![...modules].some((m) => m.exports.some((e) => `${m.id}:${e.name}` === k))) clashes.push(`  stale RENAMES entry: ${k}`);
if (clashes.length) {
  console.error("gen-index: export-name problems. Add or fix an entry in RENAMES:\n" + clashes.join("\n"));
  process.exit(1);
}

const HEADER = "/* GENERATED by scripts/gen-index.mjs. Do not edit; run `npm run gen:index`. */\n";
function lines(mods, prefix) {
  return mods.filter((m) => m.exports.length).map((m) => {
    const names = m.exports.map((e) => `${e.type ? "type " : ""}${e.name}${e.as !== e.name ? ` as ${e.as}` : ""}`).join(", ");
    return `export { ${names} } from "${prefix}${m.spec.slice(2)}";`;
  });
}

const groups = new Map();
for (const m of modules) (groups.get(m.group) ?? groups.set(m.group, []).get(m.group)).push(m);

let index = HEADER + "/* Every public component, hook, type and helper in one place. Per-folder entries: @electro1207/kiln/<folder>. */\n";
for (const [g, mods] of groups) index += `\n// ${g}\n` + lines(mods, "./").join("\n") + "\n";
writeFileSync(join(KILN, "index.ts"), index);

const gdir = join(KILN, "groups");
rmSync(gdir, { recursive: true, force: true });
mkdirSync(gdir);
for (const [g, mods] of groups) writeFileSync(join(gdir, `${g}.ts`), HEADER + lines(mods, "../").join("\n") + "\n");

console.log(`gen-index: ${used.size} exports from ${modules.length} files, ${groups.size} groups -> src/kiln/index.ts, src/kiln/groups/*.ts`);
