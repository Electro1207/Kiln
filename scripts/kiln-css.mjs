#!/usr/bin/env node
/* kiln-css: the smallest CSS for an app that installs @electro1207/kiln from npm.

   styles.css makes Tailwind scan the whole package, so the CSS carries the classes of all ~200
   components. This reads which Kiln exports your source files import, follows those files' own
   imports inside the package, and writes a CSS file that tells Tailwind to scan only them:

     npx kiln-css                       # scans ./src, writes ./src/kiln-sources.css
     npx kiln-css app/src --out app/src/styles/kiln-sources.css
     npx kiln-css --watch               # rewrite while you work (pair it with your dev server)

   Then import it after the styles, in the same CSS file:
     @import "tailwindcss";
     @import "@electro1207/kiln/styles.css";
     @import "./kiln-sources.css";

   Run it before each build ("prebuild": "kiln-css"). Named imports from the package root
   (import { Button } from "@electro1207/kiln") count one by one; a folder entry imported whole
   (import("@electro1207/kiln/media"), import * as K) counts the whole folder. No dependencies. */
import { existsSync, readdirSync, readFileSync, statSync, watch, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve, sep } from "node:path";

const NAME = "@electro1207/kiln";
const args = process.argv.slice(2);
const flag = (f) => { const i = args.indexOf(f); return i < 0 ? undefined : args.splice(i, 2)[1]; };
const watching = args.includes("--watch") && args.splice(args.indexOf("--watch"), 1);
const out = resolve(flag("--out") ?? join(args[0] ?? "src", "kiln-sources.css"));
const srcDir = resolve(args[0] ?? "src");
if (!existsSync(srcDir)) { console.error(`kiln-css: no folder ${srcDir}`); process.exit(1); }

const pkgDir = dirname(createRequire(join(process.cwd(), "noop.js")).resolve(`${NAME}/package.json`));
const lib = join(pkgDir, "lib");

/* Export name -> the file that defines it, from the package entry. */
const exportsOf = (file) => {
  const map = new Map();
  for (const m of readFileSync(file, "utf8").matchAll(/import\s*\{([^}]*)\}\s*from\s*"(\.[^"]+)"/g))
    for (const n of m[1].split(",")) { const k = n.trim().split(/\s+as\s+/)[0]; if (k) map.set(k, resolve(dirname(file), m[2])); }
  return map;
};
const rootExports = exportsOf(join(lib, "index.js"));

function walk(file, seen) {
  if (seen.has(file) || !existsSync(file)) return;
  seen.add(file);
  for (const m of readFileSync(file, "utf8").matchAll(/(?:from|import)\s*\(?\s*"(\.[^"]+)"/g)) walk(resolve(dirname(file), m[1]), seen);
}

function sourceFiles(dir) {
  return readdirSync(dir).flatMap((n) => {
    if (n === "node_modules" || n.startsWith(".")) return [];
    const p = join(dir, n);
    return statSync(p).isDirectory() ? sourceFiles(p) : /\.(m?[jt]sx?)$/.test(n) ? [p] : [];
  });
}

function generate() {
  const used = new Set();
  const esc = NAME.replace(/[.*+?^${}()|[\]\\/@-]/g, "\\$&");
  for (const f of sourceFiles(srcDir)) {
    const s = readFileSync(f, "utf8");
    for (const m of s.matchAll(new RegExp(`import\\s*(\\{[^}]*\\}|\\*\\s*as\\s+\\w+|\\w+)?\\s*(?:,\\s*\\{[^}]*\\})?\\s*from\\s*["']${esc}(/[\\w-]+)?["']`, "g"))) {
      const [, spec, sub] = m;
      const entry = sub ? join(lib, "groups", `${sub.slice(1)}.js`) : join(lib, "index.js");
      if (spec?.startsWith("{")) {
        const map = sub ? exportsOf(entry) : rootExports;
        for (const n of spec.slice(1, -1).split(",")) {
          const k = n.trim().split(/\s+as\s+/)[0].replace(/^type\s+/, "");
          if (k && map.has(k)) walk(map.get(k), used);
        }
      } else walk(entry, used);
    }
    for (const m of s.matchAll(new RegExp(`import\\(\\s*["']${esc}(/[\\w-]+)?["']\\s*\\)`, "g")))
      walk(m[1] ? join(lib, "groups", `${m[1].slice(1)}.js`) : join(lib, "index.js"), used);
  }
  const rel = (p) => relative(dirname(out), p).split(sep).join("/");
  const files = [...used].filter((p) => !p.includes(`${sep}groups${sep}`) && p !== join(lib, "index.js")).sort();
  const css = `/* GENERATED by kiln-css from the ${NAME} imports in ${relative(process.cwd(), srcDir) || "."}. Do not edit; run kiln-css again.
   Tailwind scans only the ${files.length} package files this app uses, instead of all of them. */
@source not "${rel(lib)}";
${files.map((p) => `@source "${rel(p)}";`).join("\n")}
`;
  let before = "";
  try { before = readFileSync(out, "utf8"); } catch { /* first run: nothing written yet */ }
  if (css !== before) {
    writeFileSync(out, css);
    console.log(`kiln-css: ${files.length} Kiln files -> ${relative(process.cwd(), out)}`);
  }
}

generate();
if (watching) {
  let t;
  watch(srcDir, { recursive: true }, (_, f) => {
    if (!f || resolve(srcDir, f) === out) return;
    clearTimeout(t);
    t = setTimeout(generate, 100);
  });
  console.log(`kiln-css: watching ${relative(process.cwd(), srcDir) || "."}`);
}
